#!/usr/bin/env python3
"""Bind real compiler dumps to captured kernels and extract this regression's TMEM ranges.

This is a narrow static audit of the upstream 128-row f32/colStride=1 test.
Compiler IR is never presented as a sampled hardware event or generic detector.
"""
import argparse
import gzip
import hashlib
import json
from pathlib import Path
import re
import subprocess
import tmem_compare_repro as audit


def sha(raw): return hashlib.sha256(raw).hexdigest()
def insist(value, msg):
    if not value: raise ValueError(msg)


def allocations(body):
    lines = body.splitlines(); constants = {}; alloc = {}; stores = []; selects = {}; loads = []
    insist('colStride = 1' in body, 'unsupported TMEM layout')
    for lineno, line in enumerate(lines, 1):
        constant = re.search(r'(%[\w.$]+) = arith.constant dense<([\d.eE+\-]+)> : tensor<\d+x\d+xf32', line)
        if constant: constants[constant[1]] = float(constant[2])
        found = re.search(r'(%[\w.$]+) = ttng.tmem_alloc .*tensor_memory_col_offset = (\d+) : i32, tensor_memory_row_offset = (\d+) : i32.*!ttg.memdesc<(\d+)x(\d+)xf32', line)
        if found:
            name, col, row, rows, columns = found.groups(); col, row, rows, columns = map(int, [col, row, rows, columns])
            insist(rows == 128 and row == 0, 'unsupported TMEM footprint; this audit handles only this upstream test')
            alloc[name] = {'ssa': name, 'line': lineno, 'rows': rows, 'columns': columns, 'row_offset': row,
                           'column_offset': col, 'column_interval_half_open': [col, col+columns], 'raw_line': line.strip()}
        store = re.search(r'ttng.tmem_store (%[\w.$]+), (%[\w.$]+),', line)
        if store: stores.append({'line': lineno, 'value_ssa': store[1], 'destination': store[2], 'value': constants.get(store[1]), 'raw_line': line.strip()})
        select = re.search(r'(%[\w.$]+) = arith.select %[^,]+, (%[\w.$]+), (%[\w.$]+) : !ttg.memdesc', line)
        if select: selects[select[1]] = [select[2], select[3]]
        load = re.search(r' = ttng.tmem_load (%[\w.$]+)', line)
        if load: loads.append({'line': lineno, 'source': load[1], 'raw_line': line.strip()})
    def roots(name, seen=()):
        insist(name not in seen, 'cyclic selected descriptor')
        if name in alloc: return {name}
        insist(name in selects, 'unsupported descriptor definition')
        return set.union(*(roots(x, (*seen, name)) for x in selects[name]))
    hazards = []
    for load in loads:
        if load['source'] not in selects: continue
        for root in roots(load['source']):
            source = alloc[root]
            own = [s for s in stores if s['destination'] == root and s['line'] < load['line']]
            insist(len(own) == 1, 'unexpected source store multiplicity')
            for store in stores:
                if store['destination'] == root or not source['line'] < store['line'] < load['line']: continue
                target = alloc[store['destination']]
                left, right = source['column_interval_half_open'], target['column_interval_half_open']
                if max(left[0], right[0]) < min(left[1], right[1]):
                    hazards.append({'selected_source': root, 'selected_source_value': own[0]['value'],
                                    'overwriting_allocation': store['destination'], 'overwriting_value': store['value'],
                                    'overlap_columns_half_open': [max(left[0], right[0]), min(left[1], right[1])],
                                    'store_line': store['line'], 'selected_load_line': load['line'],
                                    'scope': 'Static possible selected-source lifetime overlap in straight-line compiler IR; not a sampled GPU write/read event.'})
    return {'allocations': list(alloc.values()), 'stores': stores, 'descriptor_selects': selects,
            'loads': loads, 'possible_selected_lifetime_overlaps': hazards}


def analyze(folder, variant, output):
    # Independently validates all captured outputs and generated bytes first.
    numeric = audit.validate(folder, variant)
    summary = json.loads((folder / 'summary.json').read_text())
    raw = gzip.decompress((folder / summary['pass_ir']['path']).read_bytes())
    text = raw.decode(); insist(text.isascii(), 'byte offsets assume ASCII dump')
    headers = list(re.finditer(r'^//.*IR Dump .*$', text, re.M))
    chunks = [text[h.end():headers[i+1].start() if i+1 < len(headers) else len(text)].strip() for i, h in enumerate(headers)]
    kernels, cases = {}, []
    for row in summary['runs']:
        case = json.loads(gzip.decompress((folder / row['artifact']['path']).read_bytes()))
        kernel = case['compiled_kernels'][0]; kernels.setdefault(kernel['hash'], kernel); cases.append(case)
    starts = {}
    for key in kernels:
        glir = (folder / 'compiler' / key / 'kernel.glir').read_text().strip()
        matches = [i for i, chunk in enumerate(chunks) if chunk == glir]
        insist(len(matches) == 1, 'GLIR does not uniquely bind the compiler stream')
        starts[key] = matches[0]
    boundaries = sorted([*starts.values(), len(headers)])
    compiled = []
    for key, kernel in kernels.items():
        begin = starts[key]; end = boundaries[boundaries.index(begin)+1]
        ttgir = (folder / 'compiler' / key / 'kernel.ttgir').read_text().strip()
        ttgir_matches = [i for i in range(begin, end) if chunks[i] == ttgir]
        insist(ttgir_matches, 'TTGIR does not bind the same compiler invocation')
        indices = [i for i in range(begin, end) if 'Before TritonTensorMemoryAllocationPass:' in headers[i].group()]
        insist(len(indices) == 1, 'expected one allocation boundary per compiled kernel')
        index = indices[0]; after = index+1
        insist(after < end and 'Before TritonGPUProxyFenceInsertion:' in headers[after].group(), 'unexpected following pass boundary')
        pre, post = chunks[index], chunks[after]
        extract = allocations(post)
        spec = json.loads(kernel['specialization_data'])
        metadata = json.loads((folder / 'compiler' / key / 'kernel.json').read_text())
        tmem = int(re.search(r'ttg.tensor_memory_size = (\d+)', post)[1])
        insist(tmem == metadata['tmem_size'], 'post-allocation IR and compiled metadata disagree')
        saved = {}
        for label, chunk, at in [('before-allocation', pre, index), ('before-next-pass', post, after)]:
            dest = output / f'{variant}-{len(compiled):02d}-{label}.mlir'; dest.write_text(chunk+'\n')
            saved[label] = {'path': dest.name, 'sha256': sha(dest.read_bytes()),
                            'dump_header_index': at, 'original_byte_start': headers[at].end(),
                            'original_byte_end': headers[at+1].start() if at+1<len(headers) else len(raw)}
        case_rows = []
        for case in cases:
            if case['compiled_kernels'][0]['hash'] != key: continue
            selected = case['outputs'][0]; expected = selected['reference_value']
            matching = [h for h in extract['possible_selected_lifetime_overlaps'] if h['selected_source_value'] == expected]
            values = set(selected['actual'])
            case_rows.append({'id': case['id'], 'parameters': case['parameters'], 'expected_selected_value': expected,
                              'actual_selected_values': sorted(values), 'numeric_correct': case['numeric_correct'],
                              'selected_source_static_overlap': bool(matching),
                              'static_overlap_agrees_with_observed_wrong_value': bool(matching) == (not case['numeric_correct']) and
                                  (not matching or values == {h['overwriting_value'] for h in matching})})
        ptx = (folder / 'compiler' / key / 'kernel.ptx').read_text()
        compiled.append({'kernel_hash': key, 'constexpr_values': spec['constant_vals'], 'tmem_columns': tmem,
                         'binding': {'method': 'Exact GLIR and TTGIR text equality after trimming only outer whitespace; no compiler-order assumption.',
                                     'glir_header_index': begin, 'ttgir_header_indices': ttgir_matches,
                                     'glir_trimmed_sha256': sha(chunks[begin].encode())},
                         'pass_boundary': 'Pre-allocation dump followed immediately by pre-proxy-fence dump; latter is allocator output, not a hardware observation.',
                         'source_snapshots': saved, **extract, 'cases': case_rows,
                         'ptx_version': re.search(r'^\.version (.*)$', ptx, re.M)[1],
                         'ptx_target': re.search(r'^\.target (.*)$', ptx, re.M)[1]})
    return {'variant': variant, 'summary_sha256': numeric['summary_sha256'], 'source_commit': numeric['source_commit'],
            'pass_ir_uncompressed_sha256': sha(raw), 'pass_ir_bytes': len(raw), 'kernels': compiled,
            'unique_compiled_kernels': len(compiled), 'full_output_cases': len(cases),
            'static_runtime_consistency_cases': sum(c['static_overlap_agrees_with_observed_wrong_value'] for k in compiled for c in k['cases'])}


def main():
    p = argparse.ArgumentParser(description=__doc__); p.add_argument('--modal', type=Path, required=True)
    p.add_argument('--build-manifest', type=Path, required=True); p.add_argument('--output', type=Path, required=True)
    args = p.parse_args(); root = args.modal.resolve(); out = args.output.resolve(); out.mkdir(parents=True, exist_ok=False)
    remote = json.loads((root/'summary.json').read_text()); build_raw = args.build_manifest.read_bytes(); build = json.loads(build_raw)
    insist(remote['source_sha256']['tmem_build_manifest.json'] == sha(build_raw), 'remote build manifest changed')
    gpu_command = next(x for x in remote['execution']['commands'] if x['name'] == 'gpu_identity')
    gpu_raw = (root/gpu_command['stdout']['path']).read_bytes()
    insist(sha(gpu_raw) == gpu_command['stdout']['sha256'], 'GPU identity output changed')
    rows = [analyze(root/'artifacts'/variant, variant, out) for variant in ['before', 'after']]
    tools = []
    for item in build['builds']:
        observed = json.loads((root/'artifacts'/item['variant']/'summary.json').read_text()); wheel = item['wheels'][0]
        insist(observed['wheel_sha256'] == wheel['sha256'], 'runtime wheel identity mismatch')
        members = {Path(x['path']).name: x for x in wheel['compiler_members'] if '/nvidia/' in x['path'] or x['path'].endswith('/libtriton.so')}
        insist(observed['libtriton_sha256'] == members['libtriton.so']['sha256'], 'runtime native compiler identity mismatch')
        insist(observed['cuobjdump']['sha256'] == members['cuobjdump']['sha256'], 'runtime disassembler identity mismatch')
        tools.append({'variant': item['variant'], 'module_version': observed['triton_version'],
                      'distribution_version': observed['triton_distribution_version'], 'libtriton_sha256': observed['libtriton_sha256'],
                      'ptxas_blackwell_pinned_version': item['nvidia_toolchain_info']['ptxas-blackwell'],
                      'ptxas_blackwell_wheel_member': members['ptxas-blackwell'],
                      'ptxas_identity_scope': 'Pinned wheel member hash and target-selected backend; remote assembler process executable was not separately traced.',
                      'observed_cuobjdump': observed['cuobjdump'], 'torch_version': observed['torch_version'],
                      'torch_cuda_runtime': observed['torch_cuda']})
    result = {'schema': 'natural-tmem-compiler-lifetime-evidence-v1', 'modal_summary_sha256': sha((root/'summary.json').read_bytes()),
              'gpu_identity_observed_stdout': gpu_raw.decode().strip(), 'build_manifest_sha256': sha(build_raw),
              'analysis_source_sha256': sha(Path(__file__).read_bytes()), 'variants': rows, 'toolchains': tools,
              'limits': ['Static IR column intervals are compiler evidence, not hardware address samples or timing.',
                         'Only this upstream straight-line 128-row float32 colStride=1 case is parsed; this is not an evaluated generic bug detector.',
                         'The distinct 3/5/7 values bind source writers to observed outputs in this regression; no internal hardware version tag is sampled.',
                         'One real upstream compiler defect, tested with 16 parameter cases per compiler; not 16 independent real bugs.']}
    (out/'summary.json').write_text(json.dumps(result, indent=2)+'\n')
    print(json.dumps({'output':str(out),'kernels':[x['unique_compiled_kernels']for x in rows],
                      'consistent_cases':[x['static_runtime_consistency_cases']for x in rows]}))


if __name__ == '__main__': main()
